# Reverse mapping for recovery
REVERSE_VOCABULARY: Dict[str, str] = {v: k for k, v in CAVEMAN_VOCABULARY.items()}


@dataclass
class CompressionResult:
    original_text: str
    compressed_text: str
    tokens_before: int
    tokens_after: int
    tokens_saved: int
    compression_ratio: float
    recovery_ref: str


class CavemanCompressor:
    """Deterministic caveman-style token compressor."""

    def __init__(self, mode: CompressionMode = CompressionMode.COMPRESS, profile: CompressionProfile = CompressionProfile.FULL_SAFE):
        self.mode = mode
        self.profile = profile
        self._build_patterns()

    def _build_patterns(self) -> None:
        """Build regex patterns for vocabulary replacement."""
        # Sort by length descending to match longer terms first
        sorted_terms = sorted(CAVEMAN_VOCABULARY.keys(), key=len, reverse=True)
        self.patterns = [(re.compile(rf"\b{re.escape(term)}\b", re.IGNORECASE), CAVEMAN_VOCABULARY[term]) for term in sorted_terms]

    def _estimate_tokens(self, text: str) -> int:
        """Rough token estimation: ~4 chars per token for English."""
        return max(1, len(text) // 4)

    def compress(self, text: str, session_id: str, request_id: str) -> CompressionResult:
        """Compress text using caveman vocabulary."""
        if self.mode == CompressionMode.PASSTHROUGH:
            tokens = self._estimate_tokens(text)
            return CompressionResult(
                original_text=text,
                compressed_text=text,
                tokens_before=tokens,
                tokens_after=tokens,
                tokens_saved=0,
                compression_ratio=1.0,
                recovery_ref="",
            )

        compressed = text
        for pattern, replacement in self.patterns:
            compressed = pattern.sub(replacement, compressed)

        tokens_before = self._estimate_tokens(text)
        tokens_after = self._estimate_tokens(compressed)
        tokens_saved = tokens_before - tokens_after
        compression_ratio = tokens_after / tokens_before if tokens_before > 0 else 1.0

        # Generate recovery reference
        recovery_data = {
            "original_hash": hashlib.sha256(text.encode()).hexdigest()[:16],
            "compressed_hash": hashlib.sha256(compressed.encode()).hexdigest()[:16],
            "session_id": session_id,
            "request_id": request_id,
        }
        recovery_ref = f"ccr://ccr_obj_{hashlib.sha256(json.dumps(recovery_data, sort_keys=True).encode()).hexdigest()[:24]}"

        return CompressionResult(
            original_text=text,
            compressed_text=compressed,
            tokens_before=tokens_before,
            tokens_after=tokens_after,
            tokens_saved=max(0, tokens_saved),
            compression_ratio=compression_ratio,
            recovery_ref=recovery_ref,
        )

    def recover(self, compressed_text: str, recovery_ref: str) -> Optional[str]:
        """Attempt to recover original text from compressed (advisory only)."""
        # In a real implementation, this would look up the recovery store
        # For now, we return None to indicate recovery requires the store
        return None


